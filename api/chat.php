شخصیت را در سه بعد می‌توان درک کرد:

بعد افقی (عملکرد اجتماعی): آنچه شخصیت در تعاملات روزانه نشان می‌دهد — رفتار اجتماعی، روابط، شغل، عادات ظاهری.

بعد عمودی (لایه‌های درونی): از هویت سطحی تا ناخودآگاه عمیق — شامل شش لایه معماری پیشینه.

عمق ناخودآگاه: آرکی‌تایپ‌های یونگ، زخم‌های فراموش‌شده، الگوهای ازلی که رفتار را از زیر هدایت می‌کنند.


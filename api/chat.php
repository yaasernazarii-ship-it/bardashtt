متد استراسبرگ (Method Acting)
═══════════════════════════════════════

لی استراسبرگ یکی از مهم‌ترین استادان بازیگری قرن بیستم بود. این متد به ویژه در Actors Studio در نیویورک آموزش داده می‌شد. بازیگران مشهور مثل مارلون براندو، آل پاچینو و رابرت دنیرو تحت تأثیر این روش بودند.

تکنیک‌های اصلی:
• حافظه عاطفی (Affective Memory): بازیگر تجربه واقعی مشابهی را از گذشته‌اش به یاد می‌آورد تا احساسات مرتبط را فعال کند
• حافظه حسی (Sense Memory): بازیگر جزئیات حسی یک تجربه را بازآفرینی می‌کند — بوها، صداها، بافت‌ها، دما

چالش‌ها: استفاده بیش از حد از حافظه عاطفی ممکن است بازیگر را از صحنه و پارتنر جدا کند. همه بازیگران نمی‌توانند از خاطرات شخصی به راحتی استفاده کنند.


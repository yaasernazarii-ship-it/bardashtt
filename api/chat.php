اصطلاحات فنی سینما
═══════════════════════════════════════

نما (Shot): واحد تصویری فیلم
• نمای کامل (Full Shot / FS): تمام قد بازیگر
• نمای متوسط (Medium Shot / MS): از کمر به بالا
• نمای نزدیک (Close-Up / CU): صورت
• نمای خیلی نزدیک (Extreme Close-Up / ECU): چشم یا دهان
• نمای عمومی (Establishing Shot): معرفی محیط

دوربین:
• پن (Pan): چرخش افقی دوربین
• تیلت (Tilt): چرخش عمودی دوربین
• ترک (Tracking): حرکت دوربین همراه سوژه
• دولی (Dolly): حرکت دوربین روی ریل

تدوین:
• برش (Cut): تغییر ناگهانی از یک نما به دیگری
• دیزالو (Dissolve): تغییر تدریجی با همپوشانی دو نما
• فلش‌بک (Flashback): بازگشت به گذشته

نور:
• نور اصلی (Key Light): نور اصلی روی سوژه
• نور پس‌زمینه (Back Light): نور از پشت
• نور پر (Fill Light): نور برای حذف سایه‌های تند


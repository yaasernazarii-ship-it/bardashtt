تکنیک‌های بازیگری کلاسیک
═══════════════════════════════════════

استانیسلاوسکی:
• «اگر جادویی»: اگر من در این موقعیت بودم چه می‌کردم؟
• «شرایط داده‌شده»: همه اطلاعاتی که متن می‌دهد را باور کن
• «هدف فوری» vs «هدف اصلی»: هر صحنه یک هدف فوری دارد که در خدمت هدف کلی است
• «کنش‌های فیزیکی»: از عمل فیزیکی شروع کن، احساس خودش می‌آید

مایزنر:
• «واقعی زندگی کردن در شرایط خیالی»
• تمرین تکرار: انتقال توجه از خود به پارتنر
• «واکنش صادقانه در لحظه»

متد اکتینگ (استراسبرگ):
• حافظه عاطفی: استفاده از تجربه شخصی مشابه
• حافظه حسی: بازآفرینی جزئیات حسی تجربه

برشت (Verfremdungseffekt / V-effekt / فاصله‌گذاری):
• بازیگر کاملاً در شخصیت «غرق» نمی‌شود
• اجرای نقش با آگاهی از اینکه «بازی» می‌کند
• هدف: تحریک تفکر انتقادی تماشاگر، نه همذات‌پنداری عاطفی


مشکل اول: بازیگر ممکن است بیش از حد در ذهن خود درگیر شود — وقتی تمرکز بازیگر روی تکنیک‌ها و تحلیل‌های پیچیده باشد، ارتباط او با لحظه زنده صحنه کاهش می‌یابد.

مشکل دوم: تلاش مستقیم برای ایجاد احساس — بسیاری از بازیگران فکر می‌کنند برای یک صحنه موفق باید ابتدا احساس مشخصی را در خود ایجاد کنند. این تلاش اغلب باعث فشار روانی و بازی‌های مصنوعی می‌شود.

مشکل سوم: جدا شدن بازیگر از هدف عملی شخصیت — وقتی تمرکز اصلی بر احساس باشد، خواسته واقعی شخصیت فراموش می‌شود.

راه‌حل متد پنج سوال:
به جای تمرکز مستقیم بر احساس، تمرکز را روی ساختار رفتار انسانی قرار بده. بازیگر پنج پرسش اساسی را بررسی می‌کند که ساختار تصمیم‌گیری و کنش شخصیت را روشن می‌کنند.


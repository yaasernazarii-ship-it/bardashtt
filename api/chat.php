بیداری ۵ حس برای بازیگر
═══════════════════════════════════════

تمرینات حسی یکی از پایه‌های آموزش بازیگری است. هدف: بازیگر از حواس خود کاملاً آگاه باشد.

بینایی: تمرکز روی جزئیات محیط، رنگ‌ها، نور، حرکت
شنوایی: گوش دادن فعال به صداها، ریتم‌ها، سکوت‌ها
لامسه: احساس بافت اشیا، دما، وزن
بویایی: توجه به بوهای محیط — بوی قوی‌ترین محرک حافظه است
چشایی: حضور در لحظه از طریق طعم


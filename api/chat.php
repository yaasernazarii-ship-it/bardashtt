سیستم استانیسلاوسکی
═══════════════════════════════════════

کنستانتین استانیسلاوسکی یکی از تأثیرگذارترین چهره‌های تاریخ بازیگری است. هدف اصلی: بازیگر بتواند به جای نمایش احساسات، رفتار انسانی واقعی را روی صحنه بازآفرینی کند.

مفاهیم کلیدی:
• شرایط داده‌شده (Given Circumstances): تمام اطلاعات متن نمایشنامه درباره شخصیت و موقعیت
• اگر جادویی (Magic If): «اگر من در این موقعیت بودم چه می‌کردم؟» — کاهش فاصله بین بازیگر و شخصیت
• هدف (Objective): هر شخصیت در هر صحنه چیزی می‌خواهد — این نیروی رفتار را هدایت می‌کند
• روش کنش‌های فیزیکی: تمرکز روی عمل فیزیکی به جای احساس مستقیم
• تمرکز و تخیل: بازیگر باید کاملاً در لحظه حاضر باشد

نقص: بعضی بازیگران در تخیل غرق می‌شوند و ارتباطشان با لحظه واقعی از بین می‌رود.


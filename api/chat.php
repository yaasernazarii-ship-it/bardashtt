متد مایزنر
═══════════════════════════════════════

سنفورد مایزنر یکی دیگر از استادان بزرگ بازیگری بود که روش متفاوتی برای رسیدن به صداقت ارائه داد. معتقد بود بسیاری از بازیگران بیش از حد در ذهن خود درگیر می‌شوند.

تعریف مایزنر از بازیگری: «بازیگری یعنی زندگی کردن صادقانه در شرایط خیالی.»

تمرین معروف «تکرار» (Repetition Exercise):
دو بازیگر روبروی یکدیگر می‌نشینند و یک جمله ساده را بارها تکرار می‌کنند. هدف: انتقال توجه بازیگر از درون ذهنش به پارتنر مقابل. واکنش‌های طبیعی زمانی ظاهر می‌شوند که بازیگر واقعاً به رفتار طرف مقابل پاسخ می‌دهد.

محدودیت مایزنر: اگر بازیگر درک دقیقی از اهداف و انگیزه‌های شخصیت نداشته باشد، واکنش‌هایش ممکن است پراکنده یا بی‌جهت به نظر برسند.


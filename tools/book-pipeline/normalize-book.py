#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""نرمال‌سازی سبکِ متن استخراج‌شدهٔ کتاب.

متن PDF سه ایراد فونتی سیستماتیک دارد:
 1) ترکیب «لا» به‌صورت «ال» درآمده (طالیی → طلایی)
 2) حرف «ب» گاهی به تشدید تبدیل شده (منّع → منبع)
 3) فاصله‌های اضافیِ ناشی از هم‌ترازیِ متن داخل کلمه‌ها

اینجا فقط دو مورد اول (که قابل اعتمادند) اصلاح می‌شود؛ حدس زدنِ
فاصله‌ها می‌تواند معنا را خراب کند، پس دست نخورده می‌ماند.
"""
import re
import sys

# کلمه‌هایی که «لا» در آن‌ها جابه‌جا شده. فهرست دستی است تا کلمه‌های
# درستی مثل «سال» یا «حال» قربانی نشوند.
LA_FIXES = {
    'طالیی': 'طلایی', 'خالصه': 'خلاصه', 'معموالً': 'معمولاً', 'مثالً': 'مثلاً',
    'اصالً': 'اصلاً', 'انقالب': 'انقلاب', 'پالک': 'پلاک', 'کالم': 'کلام',
    'االن': 'الان', 'تالش': 'تلاش', 'اخالق': 'اخلاق', 'اطالعات': 'اطلاعات',
    'اعالم': 'اعلام', 'کامال': 'کاملا', 'کامالً': 'کاملاً', 'باال': 'بالا',
    'باالتر': 'بالاتر', 'خالق': 'خلاق', 'خالقیت': 'خلاقیت', 'مالقات': 'ملاقات',
    'عالقه': 'علاقه', 'عالمت': 'علامت', 'سالح': 'سلاح', 'اسالم': 'اسلام',
    'جالل': 'جلال', 'مالیم': 'ملایم', 'قالب': 'قالب', 'انفعال': 'انفعال',
    'استقالل': 'استقلال', 'اختالل': 'اختلال', 'اختالف': 'اختلاف',
    'انتقال': 'انتقال', 'تعالی': 'تعالی', 'مطالعه': 'مطالعه',
    'دالیل': 'دلایل', 'داللت': 'دلالت', 'اوالً': 'اولاً', 'ثانیاً': 'ثانیاً',
    'بالفاصله': 'بلافاصله', 'سالها': 'سال‌ها', 'ایده': 'ایده',
    'کالبد': 'کالبد', 'خالء': 'خلأ', 'مالل': 'ملال', 'جالب': 'جالب',
    'االیه': 'الایه', 'اعالء': 'اعلاء', 'امال': 'املا', 'تخیالت': 'تخیلات',
    'تجلی': 'تجلی', 'حالت': 'حالت', 'عمال': 'عملا', 'عمالً': 'عملاً',
    'متعال': 'متعال', 'اجالس': 'اجلاس', 'اطالق': 'اطلاق', 'انزال': 'انزال',
    'ابتال': 'ابتلا', 'استیال': 'استیلا', 'اشتغال': 'اشتغال',
}

def fix(text: str) -> str:
    # «ب» که به تشدید تبدیل شده
    text = text.replace('\u0651', 'ب')
    for bad, good in LA_FIXES.items():
        text = text.replace(bad, good)
    # خط‌های خالیِ پشت‌سرهم را کوتاه کن تا حجم بی‌دلیل بالا نرود
    text = re.sub(r'\n{3,}', '\n\n', text)
    # فاصله‌های تکراریِ ناشی از هم‌ترازی
    text = re.sub(r'[ \t]{2,}', ' ', text)
    return text

if __name__ == '__main__':
    src, dst = sys.argv[1], sys.argv[2]
    with open(src, encoding='utf-8') as f:
        raw = f.read()
    out = fix(raw)
    with open(dst, 'w', encoding='utf-8') as f:
        f.write(out)
    print(f'OK {dst} ({len(out):,} کاراکتر)')

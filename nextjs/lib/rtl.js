// آماده‌سازی متن فارسی برای رندر در PDF با pdfkit.
// pdfkit خودش حروف فارسی را می‌چسباند و کلمات را راست‌به‌چپ می‌چیند، اما هر
// «توکن چپ‌به‌راست» (لاتین، عدد، URL) را داخل جریان RTL معکوس می‌کند. با معکوس‌کردنِ
// پیش‌دستانهٔ این توکن‌ها، معکوس‌سازی pdfkit خنثی شده و در ترتیب درست نمایش داده می‌شوند.
// خروجی باید با گزینهٔ { features: [] } رندر شود.
const reverseRun = (m) => m.split('').reverse().join('');

export function shape(text) {
  return String(text ?? '')
    // رشته‌های لاتین/عدد/URL (حروف انگلیسی، ارقام، و نشانه‌های آدرس مثل / : . @)
    .replace(/[A-Za-z0-9][A-Za-z0-9/:._@%+\-#?=&~]*/g, reverseRun)
    // ارقام فارسی
    .replace(/[۰-۹]+/g, reverseRun);
}
